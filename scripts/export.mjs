#!/usr/bin/env node
// Builds ./export: the same crews for agents that are not Claude Code
// (OpenAI Codex CLI, GitHub Copilot, Cursor, anything else). Reads the plugins
// in ./plugins and never writes to them.
//
//   node scripts/export.mjs                   # every plugin -> ./export
//   node scripts/export.mjs --packs crew      # one plugin only
//   node scripts/export.mjs --out /tmp/dist   # write elsewhere
//   node scripts/export.mjs --check           # exit 1 if ./export is stale (CI)

import {
  readFileSync, writeFileSync, readdirSync, mkdirSync, rmSync,
  existsSync, statSync, chmodSync,
} from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGINS = join(ROOT, 'plugins');
const BANNER = '<!-- generated by scripts/export.mjs. Do not edit by hand. -->';

/* --------------------------------------------------------------- rewriting */

// The plugin sources assume Claude Code: subagents, a Skill tool, agent memory.
// Nothing else has those, so the portable build says what to do instead.
const REPLACE = [
  [/\b(crew|office|council):([a-z][a-z-]*)/g, '$1-$2'],
  [/CLAUDE\.md/g, 'AGENTS.md'],
  [/Claude Code/g, 'your coding agent'],
  [/You, the main session, orchestrate\./g, 'You orchestrate the roles yourself, one at a time.'],
  // Four wordings in the sources; keep each one's punctuation intact.
  [/\*\*Subagents don't see this conversation\.\*\*/g, '**A role step starts from its brief, not from this conversation.**'],
  [/\*\*Subagents don't see this conversation\*\*/g, '**a role step starts from its brief, not from this conversation**'],
  [/Subagents don't see this conversation:/g, 'A role step starts from its brief, not from this conversation:'],
  [/Subagents don't see this conversation,/g, 'A role step starts from its brief, not from this conversation,'],
  [/\bSubagents\b/g, 'Role steps'],
  [/\bSubagent\b/g, 'Role step'],
  [/\bsubagents\b/g, 'role steps'],
  [/\bsubagent\b/g, 'role step'],
  [/\bAskUserQuestion\b/g, 'a direct question'],
  [/^## Memory$/gm, '## Notes worth keeping'],
  [
    /Your memory is [^.]*\./g,
    "Nothing you learn here survives the session. Put durable learnings in the repo's `AGENTS.md`, or in a notes file the user keeps, and say that you did.",
  ],
];

const rewrite = (text) => REPLACE.reduce((t, [re, to]) => t.replace(re, to), text ?? '');

/* ----------------------------------------------------------------- targets */

const TARGETS = {
  codex: {
    label: 'OpenAI Codex CLI',
    roleDir: 'codex/crew/agents',
    roleRef: '~/.codex/crew/agents',
    args: '$ARGUMENTS',
    agent: (pack, a) => ({
      path: `codex/prompts/${pack}-${a.name}.md`,
      body: wrap(roleDoc(pack, a, '$ARGUMENTS')),
    }),
    workflow: (pack, s, t) => ({
      path: `codex/prompts/${pack}-${s.name}.md`,
      body: wrap(workflowDoc(pack, s, t)),
    }),
  },
  copilot: {
    label: 'GitHub Copilot (VS Code)',
    roleDir: 'copilot/.github/crew/agents',
    roleRef: '.github/crew/agents',
    args: '${input:task:What should be done?}',
    agent: (pack, a) => ({
      path: `copilot/.github/chatmodes/${pack}-${a.name}.chatmode.md`,
      body: fm({ description: rewrite(a.description), tools: copilotTools(a) })
        + wrap(roleDoc(pack, a, 'the request in the chat')),
    }),
    workflow: (pack, s, t) => ({
      path: `copilot/.github/prompts/${pack}-${s.name}.prompt.md`,
      body: fm({ mode: 'agent', description: rewrite(s.description) }) + wrap(workflowDoc(pack, s, t)),
    }),
  },
  cursor: {
    label: 'Cursor',
    roleDir: 'cursor/.cursor/crew/agents',
    roleRef: '.cursor/crew/agents',
    args: 'the request below',
    agent: (pack, a) => ({
      path: `cursor/.cursor/rules/${pack}-${a.name}.mdc`,
      body: fm({ description: rewrite(a.description), alwaysApply: 'false' })
        + wrap(roleDoc(pack, a, 'the request below')),
    }),
    workflow: (pack, s, t) => ({
      path: `cursor/.cursor/commands/${pack}-${s.name}.md`,
      body: wrap(workflowDoc(pack, s, t)),
    }),
  },
  generic: {
    label: 'Any other agent (Aider, Cline, opencode, Gemini CLI, plain prompts)',
    roleDir: 'generic/crew/agents',
    roleRef: 'crew/agents',
    args: 'the request below',
    agent: (pack, a) => ({
      path: `generic/crew/agents/${pack}-${a.name}.md`,
      body: wrap(roleDoc(pack, a, 'the request below')),
    }),
    workflow: (pack, s, t) => ({
      path: `generic/crew/workflows/${pack}-${s.name}.md`,
      body: wrap(workflowDoc(pack, s, t)),
    }),
  },
};

/* ------------------------------------------------------------------- utils */

const wrap = (body) => `${BANNER}\n\n${body.trimEnd()}\n`;

function fm(fields) {
  const lines = Object.entries(fields)
    .filter(([, v]) => v != null && v !== '')
    .map(([k, v]) => `${k}: ${v}`);
  return `---\n${lines.join('\n')}\n---\n\n`;
}

function parseDoc(file) {
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  const meta = {};
  if (m) {
    for (const line of m[1].split('\n')) {
      const i = line.indexOf(':');
      if (i > 0 && !line.startsWith(' ')) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return { meta, body: (m ? raw.slice(m[0].length) : raw).trim() };
}

const toolList = (v) => (v || '').split(',').map((s) => s.trim()).filter(Boolean);
const WRITE_TOOLS = ['Write', 'Edit', 'NotebookEdit'];

// A role is read-only when its allowlist has no write tool, or its denylist
// takes the write tools away, or the description says so.
function isReadOnly(a) {
  if (/Read-only/i.test(a.description || '')) return true;
  if (a.tools) return !toolList(a.tools).some((t) => WRITE_TOOLS.includes(t));
  return toolList(a.disallowedTools).some((t) => WRITE_TOOLS.includes(t));
}

const copilotTools = (a) =>
  isReadOnly(a) ? "['codebase', 'search', 'usages', 'fetch', 'problems']" : undefined;

function guardrails(a) {
  const lines = isReadOnly(a)
    ? ['- **Read-only role.** Do not create, edit or delete any file, and do not run commands that change state. Report findings; the user or another role applies them.']
    : ['- Change only the files this task needs. Do not commit, push or deploy unless the user asks.'];
  if (a.tools) lines.push(`- Stay within this role's job: ${toolList(a.tools).join(', ')} is all the original role was allowed.`);
  lines.push('- Nothing here enforces these limits, so they are on you. If the task needs more than the role allows, say so and stop.');
  return lines.join('\n');
}

function listAgents(pack) {
  const dir = join(PLUGINS, pack, 'agents');
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
    const { meta, body } = parseDoc(join(dir, f));
    return { name: meta.name || f.replace(/\.md$/, ''), ...meta, body, src: `plugins/${pack}/agents/${f}` };
  });
}

function listSkills(pack) {
  const dir = join(PLUGINS, pack, 'skills');
  if (!existsSync(dir)) return [];
  return readdirSync(dir).sort().flatMap((d) => {
    const file = join(dir, d, 'SKILL.md');
    if (!existsSync(file)) return [];
    const { meta, body } = parseDoc(file);
    return [{ name: meta.name || d, ...meta, body, src: `plugins/${pack}/skills/${d}/SKILL.md` }];
  });
}

function packMeta(pack) {
  const file = join(PLUGINS, pack, '.claude-plugin', 'plugin.json');
  const data = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
  return { description: rewrite(data.description || ''), version: data.version || '' };
}

/* ------------------------------------------------------- document builders */

function roleDoc(pack, a, argsToken) {
  return [
    `# ${pack}-${a.name}`,
    '',
    `> Portable build of the \`${pack}\` role **${a.name}** — source: \`${a.src}\`.`,
    `> Adopt this role for ${argsToken}, then answer in the format the role asks for.`,
    '',
    `**What this role is for:** ${rewrite(a.description)}`,
    '',
    '## Guardrails',
    '',
    guardrails(a),
    '',
    '---',
    '',
    '',
  ].join('\n') + rewrite(a.body);
}

function workflowDoc(pack, s, target) {
  return [
    `# ${pack}-${s.name}`,
    '',
    `> Portable build of the \`${pack}\` workflow **${s.name}** — source: \`${s.src}\`.`,
    '>',
    '> **This host has no subagents.** The steps below were written for a session that spawns',
    '> one fresh agent per role. Play every role yourself, in order, one at a time:',
    '>',
    `> 1. Before a step, read the role file \`${target.roleRef}/${pack}-<role>.md\` and adopt it fully.`,
    '> 2. Judge only from files, diffs and command output — never from what you concluded while',
    '>    wearing an earlier role. A reviewer who trusts the coder is not reviewing.',
    '> 3. Where a step says "in parallel", run those briefs back to back instead.',
    '> 4. Keep each role\'s output as its own labelled section, so the user sees who said what.',
    '',
    `**When to run this:** ${rewrite(s.description)}`,
    '',
    '---',
    '',
    '',
  ].join('\n') + rewrite(s.body).replace(/\$ARGUMENTS/g, target.args);
}

/* ------------------------------------------------------------ build inputs */

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : fallback;
};
const CHECK = argv.includes('--check');
const OUT = resolve(ROOT, flag('out', 'export'));

const available = readdirSync(PLUGINS).filter((d) => statSync(join(PLUGINS, d)).isDirectory()).sort();
const packs = flag('packs', available.join(',')).split(',').map((s) => s.trim()).filter(Boolean);
for (const p of packs) {
  if (!available.includes(p)) throw new Error(`unknown pack: ${p} (have: ${available.join(', ')})`);
}

const files = new Map();
const put = (path, body) => files.set(path, body);

const manifest = {
  generatedFrom: 'claude-crews',
  targets: Object.fromEntries(Object.entries(TARGETS).map(([k, v]) => [k, v.label])),
  packs: {},
};

for (const pack of packs) {
  const agents = listAgents(pack);
  const skills = listSkills(pack);
  manifest.packs[pack] = { ...packMeta(pack), roles: agents.map((a) => a.name), workflows: skills.map((s) => s.name) };

  for (const t of Object.values(TARGETS)) {
    for (const a of agents) {
      const { path, body } = t.agent(pack, a);
      put(path, body);
      // Every target also carries the plain role files its workflows read.
      put(`${t.roleDir}/${pack}-${a.name}.md`, wrap(roleDoc(pack, a, 'the request below')));
    }
    for (const s of skills) {
      const { path, body } = t.workflow(pack, s, t);
      put(path, body);
    }
  }
}

// The office crew reads a ~/knowledge base; ship the template so it can be seeded.
if (packs.includes('office')) {
  const tpl = join(PLUGINS, 'office', 'templates', 'knowledge');
  if (existsSync(tpl)) {
    for (const abs of walk(tpl)) put(`knowledge-template/${relative(tpl, abs)}`, readFileSync(abs, 'utf8'));
  }
}

put('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
put('AGENTS.snippet.md', agentsSnippet());
put('install.sh', installer());
put('README.md', readme());

/* ------------------------------------------------------- generated prose */

function agentsSnippet() {
  const rows = packs.flatMap((p) => [
    ...manifest.packs[p].roles.map((r) => `| \`${p}-${r}\` | role | \`crew/agents/${p}-${r}.md\` |`),
    ...manifest.packs[p].workflows.map((w) => `| \`${p}-${w}\` | workflow | plays several roles in order |`),
  ]);
  return [
    BANNER,
    '',
    '## Crew roles and workflows',
    '',
    'This repo ships prompt roles instead of one all-purpose assistant. When a task matches a role,',
    'read that role file first and work inside it. Workflows are multi-role: play each role in turn,',
    "and never let a later role inherit an earlier role's conclusions.",
    '',
    '| Name | Kind | Where |',
    '| --- | --- | --- |',
    ...rows,
    '',
    'Rules for every role: cite the file and line a claim rests on, do not commit or push unless asked,',
    'and say plainly when something is unverified.',
    '',
  ].join('\n');
}

function installer() {
  return `#!/usr/bin/env bash
# Installs the portable crews for one agent.
#
#   ./install.sh codex                 # -> ~/.codex/prompts + ~/.codex/crew
#   ./install.sh copilot [repo]        # -> <repo>/.github
#   ./install.sh cursor  [repo]        # -> <repo>/.cursor
#   ./install.sh generic [dir]         # -> <dir>/crew
#
set -euo pipefail

here="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
target="\${1:-}"
dest="\${2:-$PWD}"

copy() { mkdir -p "$2"; cp -R "$here/$1/." "$2/"; echo "  -> $2"; }

case "$target" in
  codex)
    echo "Installing for OpenAI Codex CLI"
    copy codex/prompts "$HOME/.codex/prompts"
    copy codex/crew "$HOME/.codex/crew"
    echo "Call them in codex with /crew-ship, /crew-reviewer, /council-vote, ..."
    ;;
  copilot)
    echo "Installing for GitHub Copilot into $dest"
    copy "copilot/.github" "$dest/.github"
    echo "Chat modes show up in the VS Code chat mode picker; prompts run with /crew-ship."
    ;;
  cursor)
    echo "Installing for Cursor into $dest"
    copy "cursor/.cursor" "$dest/.cursor"
    echo "Commands run with /crew-ship; rules attach when their description matches."
    ;;
  generic)
    echo "Installing plain prompt files into $dest/crew"
    copy generic/crew "$dest/crew"
    echo "Paste a role file into your agent's system prompt, or point your tool at the folder."
    ;;
  *)
    echo "usage: ./install.sh {codex|copilot|cursor|generic} [target-dir]" >&2
    exit 2
    ;;
esac

if [ -d "$here/knowledge-template" ]; then
  echo
  echo "The office crew reads ~/knowledge. Seed it once:"
  echo "  cp -R \\"$here/knowledge-template/.\\" \\"$HOME/knowledge/\\""
fi

if [ "$target" != "codex" ]; then
  echo
  echo "Optional: append AGENTS.snippet.md to the repo's AGENTS.md so the agent knows the roles exist."
fi
`;
}

function readme() {
  const lines = packs.map((p) => {
    const m = manifest.packs[p];
    return `- **\`${p}\`** — ${m.description}\n  - Roles: ${m.roles.map((r) => `\`${p}-${r}\``).join(', ')}\n  - Workflows: ${m.workflows.map((w) => `\`/${p}-${w}\``).join(', ')}`;
  });
  return [
    BANNER,
    '',
    '# The crews, for agents other than Claude Code',
    '',
    'Same roles and workflows as the Claude Code plugins in `../plugins`, reshaped for hosts with no',
    'subagents, no plugin marketplace and no per-agent model routing. Generated by',
    '`scripts/export.mjs` — change the plugins, then rerun it; never edit these files.',
    '',
    '## What is in here',
    '',
    ...lines,
    '',
    '## Install',
    '',
    '```bash',
    'git clone https://github.com/kavicka/claude-crews.git',
    'cd claude-crews/export',
    './install.sh codex                 # OpenAI Codex CLI, user-wide',
    './install.sh copilot /path/to/repo # GitHub Copilot in VS Code, per repo',
    './install.sh cursor  /path/to/repo # Cursor, per repo',
    './install.sh generic /path/to/repo # plain prompt files for any other agent',
    '```',
    '',
    '| Agent | Lands in | How you call it |',
    '| --- | --- | --- |',
    '| Codex CLI | `~/.codex/prompts/`, `~/.codex/crew/agents/` | `/crew-ship`, `/council-vote` |',
    '| Copilot (VS Code) | `.github/chatmodes/`, `.github/prompts/` | chat mode picker, `/crew-ship` |',
    '| Cursor | `.cursor/rules/`, `.cursor/commands/` | `/crew-ship`; rules attach by description |',
    '| Anything else | `crew/agents/`, `crew/workflows/` | paste into the system prompt |',
    '',
    '## What is different from the Claude Code build',
    '',
    '- **No subagents.** Each workflow tells one session to play every role in turn, re-reading the',
    '  role file before each step and judging only from files, diffs and command output. A single',
    '  context playing both coder and reviewer is weaker than two fresh agents — treat the review as',
    '  a second opinion, not an independent one.',
    '- **No model or effort routing.** `model:` and `effort:` are dropped. Give the planner, the',
    '  skeptic and the reviewer the strongest model your host offers.',
    '- **No tool enforcement.** Read-only roles carry a Guardrails block instead of an allowlist;',
    "  nothing stops a model from ignoring it, so read the diffs.",
    '- **No agent memory.** Durable learnings go into `AGENTS.md` or a notes file.',
    '- **Install is a file copy.** No marketplace, no hooks, no `/plugin update`.',
    '',
    '## Rebuild',
    '',
    '```bash',
    'node scripts/export.mjs            # regenerate export/',
    'node scripts/export.mjs --check    # CI: fail if export/ is stale',
    '```',
    '',
  ].join('\n');
}

/* ------------------------------------------------------------------ output */

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const abs = join(dir, f);
    return statSync(abs).isDirectory() ? walk(abs) : [abs];
  });
}

if (CHECK) {
  const stale = [...files].filter(([p, body]) => {
    const abs = join(OUT, p);
    return !existsSync(abs) || readFileSync(abs, 'utf8') !== body;
  }).map(([p]) => p);
  const orphans = (existsSync(OUT) ? walk(OUT).map((f) => relative(OUT, f)) : []).filter((f) => !files.has(f));
  if (stale.length || orphans.length) {
    for (const f of stale) console.error(`changed or missing: ${f}`);
    for (const f of orphans) console.error(`orphan:            ${f}`);
    console.error('\nexport/ is stale. Run: node scripts/export.mjs');
    process.exit(1);
  }
  console.log(`ok: export/ up to date (${files.size} files)`);
  process.exit(0);
}

if (existsSync(OUT)) rmSync(OUT, { recursive: true });
for (const [path, body] of files) {
  const abs = join(OUT, path);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, body);
}
chmodSync(join(OUT, 'install.sh'), 0o755);
console.log(`wrote ${files.size} files to ${relative(ROOT, OUT)}/ (packs: ${packs.join(', ')})`);
