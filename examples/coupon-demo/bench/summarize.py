"""Aggregate bench/results/*/result.json into bench/results/SUMMARY.md.

    python3 bench/summarize.py
"""
import json
import statistics
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
ORDER = ["vibe-medium", "vibe-xhigh", "crew"]


def spread(values, fmt="{:.0f}"):
    if not values:
        return "—"
    mean = statistics.mean(values)
    lo, hi = min(values), max(values)
    return fmt.format(mean) if lo == hi else f"{fmt.format(mean)} ({fmt.format(lo)}–{fmt.format(hi)})"


def main() -> None:
    runs = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*/result.json"))]
    by_variant = {v: [r for r in runs if r["variant"] == v] for v in ORDER}

    rows = []
    failures = {}
    for v, rs in by_variant.items():
        if not rs:
            continue
        s = [r["score"] for r in rs]
        failures[v] = Counter(t for x in s for t in x["hidden_failed"])
        rows.append([
            f"`{v}`",
            str(len(rs)),
            spread([x["hidden_passed"] for x in s], "{:.1f}") + " / 12",
            f"{sum(x['hidden_passed'] == 12 for x in s)} / {len(rs)}",
            spread([x["own_tests_total"] for x in s]),
            f"{sum(x['typecheck_ok'] for x in s)} / {len(rs)}",
            f"{sum(x['probe'].get('two_percent', {}).get('dependent', 0) > 0 for x in s)} / {len(rs)}",
            f"{sum(x['probe'].get('free_cart_total') == '0' for x in s)} / {len(rs)}",
            spread([r["cost_usd"] or 0 for r in rs], "${:.2f}"),
            spread([r["wall_seconds"] / 60 for r in rs], "{:.1f}") + " min",
            spread([len(r["subagents"]) for r in rs]),
        ])

    head = ["Variant", "Runs", "Hidden tests", "All 12", "Own tests after", "Typecheck",
            "Order-dependent price", "30 € cart free with GIFT25+SAVE5", "Cost per run", "Wall time", "Subagent calls"]
    lines = ["# Benchmark results", "",
             "Generated by `bench/summarize.py` from `results/*/result.json`. Mean, with min–max when runs differ.", "",
             "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    lines += ["", "## Hidden tests failed, per variant", "",
              "| Variant | Failed tests (runs) |", "|---|---|"]
    for v, c in failures.items():
        lines.append(f"| `{v}` | " + (", ".join(f"{t} ({n})" for t, n in sorted(c.items())) or "none") + " |")
    lines += ["", "## Every run", "",
              "| Run | Hidden | Failed | Own tests | Order-dependent carts (two percent coupons) | Cost | Wall | Subagents |",
              "|---|---|---|---|---|---|---|---|"]
    for r in sorted(runs, key=lambda r: (ORDER.index(r["variant"]), r["n"])):
        s = r["score"]
        dep = s["probe"].get("two_percent", {})
        lines.append(f"| {r['variant']}-{r['n']} | {s['hidden_passed']}/12 | {', '.join(s['hidden_failed']) or '—'} "
                     f"| {s['own_tests_total']} | {dep.get('dependent', '?')} / {dep.get('carts', '?')} "
                     f"| ${(r['cost_usd'] or 0):.2f} | {r['wall_seconds'] / 60:.1f} min "
                     f"| {', '.join(r['subagents']) or '—'} |")
    leaks = [f"{r['variant']}-{r['n']}" for r in runs if r.get("hidden_test_leak_suspected")]
    lines += ["", f"Transcripts mentioning the hidden tests or the original run: {', '.join(leaks) or 'none'}."]
    total = sum(r["cost_usd"] or 0 for r in runs)
    lines += [f"Total cost of all runs: ${total:.2f}.", ""]
    (RESULTS / "SUMMARY.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
